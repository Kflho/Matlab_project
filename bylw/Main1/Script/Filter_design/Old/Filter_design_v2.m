% =========================================================================
% 水印嵌入与移除器矩阵网格搜索算法 (LMI 最优设计)
% =========================================================================
clear; clc; yalmip('clear'); % 清空工作区和 YALMIP 内部变量缓存

% =========================================================================
% 1. 系统维度参数定义 (可自由调整)
% =========================================================================
nx  = 4; % 增广系统状态变量维度
nu  = 2; % 控制输入/攻击信号维度
ny  = 2; % 控制系统输出 y 的维度 (已知受控系统输出为 2x1)
nyj = 6; % 性能输出 yj 的维度 (已知性能输出为 6x1)

% =========================================================================
% 2. 优化权重与防守参数定义 (可自由调整)
% =========================================================================
epsilon_a = 1.0; % 攻击能量上限 \varepsilon_a
epsilon_r = 1.0; % 检测阈值上限/残差界限 \varepsilon_r

% =========================================================================
% 3. 网格搜索 (Grid Search) 参数定义
% =========================================================================
% 根据算法，Dw 为 2x2 正定对角矩阵 diag(alpha_1, alpha_2)
alpha_min = 0.1; % 搜索下界 (保证正定，大于0)
alpha_max = 5.0; % 搜索上界
n_s       = 0.5; % 离散网格采样步长

% =========================================================================
% 4. 增广系统已知矩阵定义 (需在此处填入具体数据)
% =========================================================================
% 这些矩阵通常由原始系统 A, B, C, D 增广得到，需由您提供具体数值
A = []; 
B = []; 
C_r_bar = []; % 与残差/攻击检测相关的观测矩阵

% =========================================================================
% 5. 初始化最优记录变量
% =========================================================================
gamma_star  = inf; % 初始最优代价设为无穷大
best_Cw     = [];  % 存储最优水印状态矩阵 Cw
best_Dw     = [];  % 存储最优水印直接前馈矩阵 Dw
best_gamma_r  = [];  % 存储最优检测灵敏度加权因子
best_gamma_a= [];  % 存储最优性能损失加权因子

% =========================================================================
% 6. 定义 YALMIP 独立决策变量 (定义在循环外，避免内存泄漏)
% =========================================================================
P       = sdpvar(nx, nx, 'symmetric');
gamma_r   = sdpvar(1, 1);
gamma_a = sdpvar(1, 1);
Z_sigma = sdpvar(nx, nx, 'symmetric');

% 待设计矩阵 Cw (2x4)
Cw      = sdpvar(ny, nx); 

% 配置 YALMIP 求解器 (推荐 SeDuMi 或 SDPT3，关闭内部输出以防刷屏)
options = sdpsettings('solver', 'sedumi', 'verbose', 0);

% =========================================================================
% 7. 开始外层循环：遍历 Dw 搜索空间
% =========================================================================
disp('开始进行网格搜索...');
iter_count = 0; % 迭代计数器

for alpha_1 = alpha_min : n_s : alpha_max
    for alpha_2 = alpha_min : n_s : alpha_max
        iter_count = iter_count + 1;
        
        % 步骤 1: 构造当前的常数矩阵 Dw (2x2 对角阵)
        Dw_current = diag([alpha_1, alpha_2]);
        
        % 步骤 2: 构造含待求解变量 Cw 和常数矩阵 Dw 的性能矩阵
        % -----------------------------------------------------------------
        % 注意：以下 C_j_bar 和 D_j_bar 需要根据您的系统物理方程进行组合。
        % 因为现在 Dw_current 是常数，Cw 是 sdpvar，这就变成了一个纯 LMI。
        % 请将您的实际矩阵组合逻辑填入此处：
        C_j_bar = []; % 例如：[C1; C2*Cw]
        D_j_bar = []; % 例如：[D1; D2*Dw_current]
        % -----------------------------------------------------------------
        
        % 步骤 3: 构建 LMI 约束条件
        Constraints = [];
        Constraints = [Constraints, P >= 0, gamma_r >= 0, gamma_a >= 0, Z_sigma >= 0];
        
        % 使用 Schur 补转化后的 LMI 分块矩阵 (保证为凸优化)
        M11 = A'*P*A - P - gamma_r * (C_r_bar' * C_r_bar);
        M12 = A'*P*B;
        M13 = C_j_bar';
        
        M21 = B'*P*A;
        M22 = B'*P*B - gamma_a * eye(nu); 
        M23 = D_j_bar';
        
        M31 = C_j_bar;
        M32 = D_j_bar;
        M33 = -eye(nyj); % 6x1 性能输出维度的负单位阵
        
        LMI_Matrix = [M11, M12, M13;
                      M21, M22, M23;
                      M31, M32, M33];
                      
        Constraints = [Constraints, LMI_Matrix <= 0];
        
        % 步骤 4: 定义目标函数并求解
        % 根据算法中“若 \gamma^t < \gamma^* 则储存”，这里的 \gamma^t 通常指综合代价函数
        Objective = epsilon_r * gamma_r + epsilon_a * gamma_a;
        
        sol = optimize(Constraints, Objective, options);
        
        % 步骤 5: 判断是否可行，并更新全局最优解
        if sol.problem == 0 % sol.problem == 0 表示求解成功且可行
            current_cost = value(Objective);
            
            % 如果当前解的目标值更小，则更新最优记录
            if current_cost < gamma_star
                gamma_star   = current_cost;
                best_Cw      = value(Cw);
                best_Dw      = Dw_current;
                best_gamma_r = value(gamma_r);
                best_gamma_a = value(gamma_a);
                
                fprintf('发现更优解! 迭代次数: %d, 综合代价: %.4f, \gamma_r: %.4f\n,\gamma_a: %.4f\n', ...
                        iter_count, gamma_star, best_gamma_r,best_gamma_a);
            end
        end
    end
end

% =========================================================================
% 8. 搜索结果输出
% =========================================================================
disp('========================================');
if gamma_star == inf
    disp('搜索失败：在设定的 Dw 网格范围内，未找到任何可行的 LMI 解。');
    disp('建议：检查增广矩阵 A, B 是否正确，或扩大 alpha 搜索范围、调整网格步长。');
else
    disp('网格搜索完成，找到全局最优的水印参数集！');
    fprintf('最优综合代价目标值 : %.6f\n', gamma_star);
    fprintf('最优检测灵敏度 \gamma: %.6f\n', best_gamma_r);
    fprintf('最优性能损失 \gamma_a: %.6f\n', best_gamma_a);
    
    disp('----------------------------------------');
    disp('设计完成的水印移除器状态空间矩阵 Cw (2x4):');
    disp(best_Cw);
    
    disp('设计完成的水印直接前馈对角矩阵 Dw (2x2):');
    disp(best_Dw);
end