%% test_08_inject_fault.m  故障注入测试
%  验证 inject_fault 对传感器故障和执行器故障的注入逻辑：
%    1. 传感器故障：在指定子系统输出叠加故障幅值
%    2. 执行器故障：在全局输入叠加故障幅值
%    3. 故障注入时刻前后数据完整性
%    4. 无传感器子系统注入传感器故障的警告

clear; clc;

% ---- 添加路径 ----
addpath(genpath('../../../../../utils/'));
addpath(genpath('../lib/'));
addpath(genpath('../scripts/'));

%% ============================================================
%  1. 准备测试数据
% ============================================================
fprintf('===== 1. 准备测试数据 =====\n\n');

T_test = 200;

% 全局矩阵格式
y_test = randn(2, T_test);    % 2 个输出 × 200 步
u_test = randn(2, T_test);    % 2 个输入 × 200 步

% cell 格式
y_cell = cell(1, 4);
y_cell{1} = randn(1, T_test);
y_cell{2} = randn(1, T_test);
y_cell{3} = [];
y_cell{4} = [];

%% ============================================================
%  2. 传感器故障 — 矩阵格式
% ============================================================
fprintf('\n===== 2. 传感器故障（矩阵格式）=====\n\n');

k_f = 100;
f_mag = 2.5;

[y_f_mat, u_f_mat] = inject_fault(y_test, u_test, 'sensor', 1, f_mag, k_f);

% 验证：故障前数据不变
assert(isequal(y_f_mat(:, 1:k_f-1), y_test(:, 1:k_f-1)), ...
    '故障前数据应保持不变');
fprintf('✓ 故障前数据不变（k=1:%d）\n', k_f-1);

% 验证：故障后数据叠加了故障幅值
err_post = y_f_mat(1, k_f:end) - y_test(1, k_f:end);
assert(all(abs(err_post - f_mag) < 1e-12), '故障幅值叠加错误');
fprintf('✓ k≥%d 时子系统 1 输出叠加 +%.1f\n', k_f, f_mag);

% 验证：其他子系统不受影响
assert(isequal(y_f_mat(2, :), y_test(2, :)), '子系统 2 不应受影响');
fprintf('✓ 子系统 2 不受传感器故障影响\n');

% 验证：输入不受影响
assert(isequal(u_f_mat, u_test), '输入不应受传感器故障影响');
fprintf('✓ 输入不受传感器故障影响\n');

%% ============================================================
%  3. 传感器故障 — cell 格式
% ============================================================
fprintf('\n===== 3. 传感器故障（cell 格式）=====\n\n');

[y_f_cell, ~] = inject_fault(y_cell, u_test, 'sensor', 2, 1.5, 50);

% 验证子系统 2 有故障
err_cell = y_f_cell{2}(:, 50:end) - y_cell{2}(:, 50:end);
assert(all(abs(err_cell - 1.5) < 1e-12), 'cell 格式故障幅值错误');
fprintf('✓ cell 格式传感器故障注入正确\n');

%% ============================================================
%  4. 执行器故障
% ============================================================
fprintf('\n===== 4. 执行器故障 =====\n\n');

[y_f_act, u_f_act] = inject_fault(y_test, u_test, 'actuator', 1, 0.8, 75);

% 验证：输入叠加故障
err_u = u_f_act(:, 75:end) - u_test(:, 75:end);
assert(all(abs(err_u(:) - 0.8) < 1e-12), '执行器故障幅值错误');
fprintf('✓ k≥75 时输入叠加 +%.1f\n', 0.8);

% 验证：输出不受直接影响
assert(isequal(y_f_act, y_test), '输出不应受执行器故障直接影响');
fprintf('✓ 输出不受执行器故障直接影响（仅通过动态传播）\n');

%% ============================================================
%  5. 无传感器子系统注入传感器故障（应警告）
% ============================================================
fprintf('\n===== 5. 无传感器子系统 =====\n\n');

warning('off', 'all');
[y_f_warn, ~] = inject_fault(y_cell, u_test, 'sensor', 3, 1.0, 50);
warning('on', 'all');

% 数据应保持不变
assert(isequal(y_f_warn{3}, y_cell{3}), '无传感器子系统不应被修改');
fprintf('✓ 无传感器子系统（3）数据不变\n');

%% ============================================================
%  6. 汇总
% ============================================================
fprintf('\n===== 测试汇总 =====\n');
fprintf('  inject_fault 正确实现故障注入：\n');
fprintf('    - 传感器故障: 指定子系统输出叠加 f_y ✓\n');
fprintf('    - 执行器故障: 全局输入叠加 f_u ✓\n');
fprintf('    - 故障时刻前后数据完整性 ✓\n');
fprintf('    - cell 与矩阵两种格式均支持 ✓\n');
fprintf('    - 无传感器子系统妥善处理 ✓\n');
